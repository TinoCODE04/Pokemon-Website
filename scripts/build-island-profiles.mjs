import { NodeIO } from '@gltf-transform/core'
import { ALL_EXTENSIONS } from '@gltf-transform/extensions'
import { dedup, weld, simplifyPrimitive, prune, meshopt } from '@gltf-transform/functions'
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from 'meshoptimizer'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready, MeshoptSimplifier.ready])
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'meshopt.decoder': MeshoptDecoder,
  'meshopt.encoder': MeshoptEncoder,
})
const source = 'public/models/pokemon-island.glb'
const original = await readFile(source)
const sourceHash = createHash('sha256').update(original).digest('hex')
const profiles = {}
for (const [name, ratio, error] of [['mobile', 0.12, 0.003], ['desktop', 0.32, 0.0015]]) {
  const document = await io.read(source)
  await document.transform(dedup(), weld())
  for (const primitive of document.getRoot().listMeshes().flatMap(mesh => mesh.listPrimitives())) {
    // The small textured water surface costs little and needs its original topology.
    if (!primitive.getMaterial()?.getBaseColorTexture()) simplifyPrimitive(primitive, { simplifier: MeshoptSimplifier, ratio, error })
  }
  await document.transform(prune(), meshopt({ encoder: MeshoptEncoder, level: 'high', quantizePosition: 16 }))
  const bytes = await io.writeBinary(document)
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12)
  const file = `pokemon-island-${name}-${hash}.glb`
  await writeFile(`public/models/${file}`, bytes)
  const triangles = document.getRoot().listMeshes().flatMap(mesh => mesh.listPrimitives()).reduce((total, primitive) => total + primitive.getIndices().getCount() / 3, 0)
  profiles[name] = { url: `/models/${file}`, bytes: bytes.byteLength, triangles }
  console.log(`${name}: ${(bytes.byteLength / 1e6).toFixed(2)} MB, ${triangles.toLocaleString()} triangles`)
}
await writeFile('src/data/islandAssets.ts', `// Generated by scripts/build-island-profiles.mjs. Original GLB is preserved.\nexport const ISLAND_ASSETS = ${JSON.stringify(profiles, null, 2)} as const\n`)
if (createHash('sha256').update(await readFile(source)).digest('hex') !== sourceHash) throw new Error('Original model changed')
